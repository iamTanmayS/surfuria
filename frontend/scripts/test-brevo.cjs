#!/usr/bin/env node
/**
 * Surfuria — Brevo Delivery Diagnostic & Health Check Tool
 * Run via: npm run test:email
 */

const fs = require('fs');
const path = require('path');

// Read .env.local (authoritative local configuration) or .env in frontend
let envPath = path.resolve(process.cwd(), '.env.local');
if (!fs.existsSync(envPath)) {
  envPath = path.resolve(process.cwd(), '.env');
}
if (!fs.existsSync(envPath)) {
  envPath = path.resolve(__dirname, '../.env.local');
}
if (!fs.existsSync(envPath)) {
  envPath = path.resolve(__dirname, '../.env');
}

if (!fs.existsSync(envPath)) {
  console.error('\n❌ No .env.local or .env file found in frontend.');
  console.log('Please copy .env.example to .env.local and configure your Brevo credentials.\n');
  process.exit(1);
}

const envContent = fs.readFileSync(envPath, 'utf8');
const env = {};
envContent.split(/\r?\n/).forEach((line) => {
  const match = line.trim().match(/^([^=]+)=(.*)$/);
  if (match && !line.trim().startsWith('#')) {
    env[match[1].trim()] = match[2].trim();
  }
});

const apiKey = env.BREVO_API_KEY || process.env.BREVO_API_KEY;
const senderEmail = env.BREVO_SENDER_EMAIL || process.env.BREVO_SENDER_EMAIL;
const senderName = env.BREVO_SENDER_NAME || process.env.BREVO_SENDER_NAME || 'Surfuria';
const recipientEmail =
  env.CONTACT_RECIPIENT_EMAIL || process.env.CONTACT_RECIPIENT_EMAIL || 'info@surfuria.com';

console.log('\n==================================================');
console.log('  SURFURIA — Brevo Transactional Email Diagnostics');
console.log('==================================================\n');

console.log(`📁 Loaded configuration from: ${envPath}`);
console.log(`🔑 Brevo API Key:           ${apiKey ? apiKey.slice(0, 15) + '...' : '❌ NOT SET'}`);
console.log(`📤 Sender Email:             ${senderEmail || '❌ NOT SET'}`);
console.log(`🏷️  Sender Name:              ${senderName}`);
console.log(`📥 Destination Recipient:    ${recipientEmail}\n`);

if (!apiKey || !senderEmail) {
  console.error('❌ Missing required configuration in .env!');
  if (!apiKey) console.error('   - BREVO_API_KEY is missing.');
  if (!senderEmail) console.error('   - BREVO_SENDER_EMAIL is missing.');
  console.log('\nPlease fill in these variables and run again.\n');
  process.exit(1);
}

console.log('📡 Sending test enquiry to Brevo API (https://api.brevo.com/v3/smtp/email)...');

const testPayload = {
  sender: {
    name: senderName,
    email: senderEmail,
  },
  to: [
    {
      name: 'Surfuria Management',
      email: recipientEmail,
    },
  ],
  subject: '[Surfuria Diagnostic] Test Delivery Verification',
  htmlContent: `
    <div style="font-family: sans-serif; padding: 24px; border: 1px solid #e7e0d5; border-radius: 8px;">
      <h2 style="color: #b77b3f; margin-top: 0;">SURFURIA — Email Delivery Test</h2>
      <p>This is an automated diagnostic test from your local environment.</p>
      <p><strong>Sender:</strong> ${senderEmail}</p>
      <p><strong>Recipient:</strong> ${recipientEmail}</p>
      <p><strong>Timestamp:</strong> ${new Date().toISOString()}</p>
      <p style="color: #25d366; font-weight: bold;">✔ If you see this, your Brevo credentials and delivery pipeline are working perfectly!</p>
    </div>
  `,
  textContent: `SURFURIA — Email Delivery Test\n\nIf you see this in your inbox, your Brevo integration is working perfectly!\nTimestamp: ${new Date().toISOString()}\nRecipient: ${recipientEmail}`,
};

fetch('https://api.brevo.com/v3/smtp/email', {
  method: 'POST',
  headers: {
    'api-key': apiKey,
    'Content-Type': 'application/json',
    Accept: 'application/json',
  },
  body: JSON.stringify(testPayload),
})
  .then(async (res) => {
    const data = await res.json().catch(() => ({}));

    if (res.ok) {
      console.log('\n✅ SUCCESS (HTTP ' + res.status + ')!');
      console.log(`📧 Test email accepted by Brevo!`);
      console.log(`🆔 Message ID: ${data.messageId || 'Generated by Brevo'}`);
      console.log(`📬 Please check the inbox of: ${recipientEmail}`);
      console.log('   (Also check the Spam/Junk folder if this is the first email sent.)\n');
      process.exit(0);
    }

    console.error(`\n❌ BREVO REJECTED THE REQUEST (HTTP ${res.status}):`);
    console.error(JSON.stringify(data, null, 2));

    if (res.status === 401 && data.message && data.message.includes('unrecognised IP address')) {
      console.log('\n🔒 IP AUTHORIZATION REQUIRED BY BREVO:');
      console.log('Brevo has security IP filtering enabled for this API key.');
      console.log('👉 Open this link in your browser to approve your IP:');
      console.log('   https://app.brevo.com/security/authorised_ips');
      console.log('   Click "Add a new IP address" and add your current IP address.');
      console.log('   (Or check your email inbox for an approval email from Brevo.)\n');
    } else if (data.message && data.message.toLowerCase().includes('sender')) {
      console.log('\n⚠️ SENDER NOT VERIFIED IN BREVO:');
      console.log(`The sender email (${senderEmail}) is not verified in Brevo.`);
      console.log('👉 Open: https://app.brevo.com/senders');
      console.log(`   Make sure ${senderEmail} is listed and verified with a green checkmark.\n`);
    }

    process.exit(1);
  })
  .catch((err) => {
    console.error('\n❌ Network error communicating with Brevo:', err.message);
    process.exit(1);
  });

